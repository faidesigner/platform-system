// ─── 실행 ─────────────────────────────────────
console.log('\n🔄 토큰 동기화 시작...\n');
try {
  console.log('[ foundation/ — 공유 토큰 ]');
  generateColorCSS();
  generateDarkCSS();
  generateColorBrandCSS();
  generateOpacityCSS();
  generateEffectsCSS();
  generateTypographyCSS();
  generateFoundationIndex();

  console.log('\n[ web/ — 웹 플랫폼 ]');
  generateWebBaseCSS();
  ensureWebIndex();

  console.log('\n[ vg/ — VGK 플랫폼 ]');
  generateVGBaseCSS();
  ensureVGIndex();

  console.log('\n✅ 동기화 완료\n');
} catch (err) {
  console.error('\n❌ 동기화 실패:', err.message);
  console.error(err.stack);
  process.exit(1);
}
