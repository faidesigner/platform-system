#!/usr/bin/env node

/**
 * JSON → CSS 토큰 동기화 스크립트
 *
 * `npm run sync` 실행 시 root/foundation/*.json 을 읽어
 * root/styles/ 하위 CSS 파일을 자동 생성합니다.
 *
 * 참조 표기법: {path.to.token} → var(--path-to-token)
 * 특수 키 "_": 상위 키만 CSS 변수명으로 사용 (예: spacing._ → --spacing)
 */

const fs = require('fs');
const path = require('path');

const ROOT       = path.resolve(__dirname, '..');
const FOUNDATION = path.join(ROOT, 'root', 'foundation');
const STYLES_OUT = path.join(ROOT, 'root', 'styles');

const generatedTokenFiles = [];

// ─── 유틸 ────────────────────────────────────

function resolveRefs(value) {
  if (typeof value !== 'string') return String(value);
  return value.replace(/\{([^}]+)\}/g, (_, p) => `var(--${p.replace(/\./g, '-')})`);
}

function flattenToVars(obj, prefix = '') {
  const vars = {};
  for (const [key, value] of Object.entries(obj)) {
    if (key === '$meta') continue;
    const varName = key === '_' ? prefix : (prefix ? `${prefix}-${key}` : key);
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      Object.assign(vars, flattenToVars(value, varName));
    } else {
      vars[`--${varName}`] = resolveRefs(value);
    }
  }
  return vars;
}

function renderVars(vars, indent = '  ') {
  return Object.entries(vars)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join('\n');
}

function diffVars(base, override) {
  return Object.fromEntries(
    Object.entries(override).filter(([k, v]) => base[k] !== v)
  );
}

function readJSON(filename) {
  return JSON.parse(fs.readFileSync(path.join(FOUNDATION, filename), 'utf-8'));
}

function writeCSS(filename, content) {
  const fullPath = path.join(STYLES_OUT, filename);
  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  fs.writeFileSync(fullPath, content, 'utf-8');
  console.log(`  ✓ root/styles/${filename}`);
  generatedTokenFiles.push(filename);
}

function filterByPrefix(vars, prefix) {
  return Object.fromEntries(
    Object.entries(vars).filter(([k]) => k.startsWith(`--${prefix}-`) || k === `--${prefix}`)
  );
}

const HEADER = '/* Generated by scripts/sync-tokens.js — DO NOT EDIT DIRECTLY */\n';

// ─── color.css ───────────────────────────────
function generateColorCSS() {
  const global   = readJSON('color-global.json');
  const semantic = readJSON('color-semantic.json');

  const globalVars = flattenToVars(global, 'color');
  const lightVars  = flattenToVars(semantic.light, 'color');

  const content = [
    HEADER + '@theme {',
    '  /* Global Colors */',
    renderVars(globalVars),
    '',
    '  /* Semantic Colors (Light) */',
    renderVars(lightVars),
    '}', '',
  ].join('\n');

  writeCSS('color.css', content);
}

// ─── dark.css ────────────────────────────────
function generateDarkCSS() {
  const semantic = readJSON('color-semantic.json');
  const darkVars  = flattenToVars(semantic.dark, 'color');

  const content = [
    HEADER + ':where(.dark) {',
    renderVars(darkVars),
    '}', '',
  ].join('\n');

  writeCSS('dark.css', content);
}

// ─── color-brand.css  (클라이언트별 브랜드 컬러) ──
function generateColorBrandCSS() {
  const brand = readJSON('color-brand.json');
  const blocks = [];

  for (const [client, tokens] of Object.entries(brand)) {
    const vars = flattenToVars(tokens, 'color');
    blocks.push(`/* ${client} */\n[data-brand='${client}'] {\n${renderVars(vars)}\n}`);
  }

  writeCSS('color-brand.css', HEADER + blocks.join('\n\n') + '\n');
}

// ─── opacity.css ─────────────────────────────
function generateOpacityCSS() {
  const opacity = readJSON('opacity.json');
  const vars = flattenToVars(opacity, 'opacity');

  writeCSS('opacity.css', HEADER + `@theme {\n${renderVars(vars)}\n}\n`);
}

// ─── spacing.css + spacing-vgk.css ───────────
function generateSpacingCSS() {
  const spacing = readJSON('spacing.json');

  // @theme: 글로벌 size + mw 레이아웃 기본값
  const sizeVars = flattenToVars(spacing.size, 'size');
  const mwVars   = flattenToVars(spacing.mw);   // prefix 없음 → --padding-*, --spacing-*, --cornerRadius-*

  const baseContent = [
    HEADER + '@theme {',
    '  /* Sizes */',
    renderVars(sizeVars),
    '',
    '  /* Padding (mw) */',
    renderVars(filterByPrefix(mwVars, 'padding')),
    '',
    '  /* Spacing (mw) */',
    renderVars(filterByPrefix(mwVars, 'spacing')),
    '',
    '  /* Corner Radius (mw) */',
    renderVars(filterByPrefix(mwVars, 'cornerRadius')),
    '}', '',
  ].join('\n');

  writeCSS('spacing.css', baseContent);

  // VGK 오버라이드
  const vgkVars = flattenToVars(spacing.vgk);

  const vgkContent = [
    HEADER + "/* VGK(Video Guide / Kiosk) 레이아웃 오버라이드 */",
    "[data-layout='vgk'] {",
    '  /* Padding */',
    renderVars(filterByPrefix(vgkVars, 'padding')),
    '',
    '  /* Spacing */',
    renderVars(filterByPrefix(vgkVars, 'spacing')),
    '',
    '  /* Corner Radius */',
    renderVars(filterByPrefix(vgkVars, 'cornerRadius')),
    '}', '',
  ].join('\n');

  writeCSS('spacing-vgk.css', vgkContent);
}

// ─── typography.css  (글로벌 폰트 원시값) ─────
function generateTypographyCSS() {
  const typo = readJSON('typography.json');
  // prefix 'font' 로 flatten → --font-family-*, --font-weight-*, --font-size-*, 등
  const vars = flattenToVars(typo, 'font');

  const sections = [
    ['/* Font Family */',       filterByPrefix(vars, 'font-family')],
    ['/* Font Weight */',       filterByPrefix(vars, 'font-weight')],
    ['/* Font Size */',         filterByPrefix(vars, 'font-size')],
    ['/* Line Height */',       filterByPrefix(vars, 'font-lineHeight')],
    ['/* Letter Spacing */',    filterByPrefix(vars, 'font-letterSpacing')],
  ];

  const body = sections
    .filter(([, v]) => Object.keys(v).length > 0)
    .map(([c, v]) => `  ${c}\n${renderVars(v)}`)
    .join('\n\n');

  writeCSS('typography.css', HEADER + `@theme {\n${body}\n}\n`);
}

// ─── typography-{m,w,k,vg}.css  (플랫폼별 타이포그래피) ──
function generatePlatformTypoCSS(jsonFile, cssFile, prefix) {
  const data = readJSON(jsonFile);

  // KO → @theme 기본값
  const koVars = flattenToVars(data.ko, prefix);
  let content = HEADER + `@theme {\n${renderVars(koVars)}\n}\n`;

  // EN / JP → lang 오버라이드 (KO와 다른 값만)
  const langMap = { en: "html[lang='en']", jp: "html[lang='jp']" };
  for (const [lang, selector] of Object.entries(langMap)) {
    if (!data[lang]) continue;
    const langVars = flattenToVars(data[lang], prefix);
    const diff = diffVars(koVars, langVars);
    if (Object.keys(diff).length > 0) {
      content += `\n${selector} {\n${renderVars(diff)}\n}\n`;
    }
  }

  writeCSS(cssFile, content);
}

// ─── effects.css ─────────────────────────────
function generateEffectsCSS() {
  const effects = readJSON('effects.json');
  const vars = flattenToVars(effects);

  const sections = [
    ['/* Shadows */',    filterByPrefix(vars, 'shadow')],
    ['/* Animations */', filterByPrefix(vars, 'animate')],
  ].filter(([, v]) => Object.keys(v).length > 0);

  const body = sections.map(([c, v]) => `  ${c}\n${renderVars(v)}`).join('\n\n');
  writeCSS('effects.css', HEADER + `@theme {\n${body}\n}\n`);
}

// ─── root/styles/index.css  (진입점 — 최초 1회만 생성) ──
function ensureStylesIndex() {
  const dest = path.join(STYLES_OUT, 'index.css');
  if (fs.existsSync(dest)) return;

  const content = `/* 폰트는 항상 최상위에서 import */
@import url('https://cdn.jsdelivr.net/gh/orioncactus/pretendard@v1.3.9/dist/web/variable/pretendardvariable-dynamic-subset.min.css');
@import '@fontsource-variable/m-plus-2';

/* Web 에서 사용하는 Tailwind Token */
@import 'tailwindcss';
@plugin "tailwindcss-animate";

/* 토큰 — foundation/index.css 에서 일괄 import */
@import '../foundation/index.css' layer(base);
@import './dark.css' layer(dark);
@import './spacing-vgk.css';
@import './color-brand.css';

@layer base {
  html {
    font-family: var(--font-family-pretendard);
    font-size: 16px;
    user-select: none;
  }

  html[lang='ko'] {
    font-family: var(--font-family-pretendard);
  }

  html[lang='jp'] {
    font-family: var(--font-family-m-plus-2);
    font-weight: 1 999;
  }

  button:focus { outline: none; }

  .prevent-select {
    -webkit-user-select: none;
    -ms-user-select: none;
    user-select: none;
  }

  input:focus {
    outline: none !important;
    box-shadow: none !important;
  }
}
`;
  fs.writeFileSync(dest, content, 'utf-8');
  console.log('  ✓ root/styles/index.css (최초 생성)');
}

// ─── root/foundation/index.css  (토큰 전용 진입점 — 자동 갱신) ──
function generateFoundationIndex() {
  const imports = generatedTokenFiles
    .filter(f => f !== 'dark.css' && f !== 'spacing-vgk.css' && f !== 'color-brand.css')
    .map(f => `@import '../styles/${f}';`)
    .join('\n');

  const content = [
    HEADER,
    '/* 토큰 전용 진입점: Tailwind 없이 CSS 변수만 필요할 때 import */',
    '/* dark.css / spacing-vgk.css / color-brand.css 는 조건부 사용이므로 별도 import 필요 */',
    '',
    imports,
    '',
  ].join('\n');

  const fullPath = path.join(FOUNDATION, 'index.css');
  fs.writeFileSync(fullPath, content, 'utf-8');
  console.log('  ✓ root/foundation/index.css');
}

// ─── 실행 ─────────────────────────────────────
console.log('\n🔄 토큰 동기화 시작...\n');
try {
  generateColorCSS();
  generateDarkCSS();
  generateColorBrandCSS();
  generateOpacityCSS();
  generateSpacingCSS();
  generateTypographyCSS();
  generatePlatformTypoCSS('typography-m.json',  'typography-m.css',  'm');
  generatePlatformTypoCSS('typography-w.json',  'typography-w.css',  'w');
  generatePlatformTypoCSS('typography-k.json',  'typography-k.css',  'k');
  generatePlatformTypoCSS('typography-vg.json', 'typography-vg.css', 'vg');
  generateEffectsCSS();
  ensureStylesIndex();
  generateFoundationIndex();
  console.log('\n✅ 동기화 완료\n');
} catch (err) {
  console.error('\n❌ 동기화 실패:', err.message);
  console.error(err.stack);
  process.exit(1);
}
